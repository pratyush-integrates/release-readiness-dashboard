"""Builds the Confluence release notes page (storage format XHTML)."""
from datetime import date
from html import escape

from .readiness import Readiness, is_blocker
from .services.jira_service import Issue

FEATURE_TYPES = {"Story", "Feature", "Epic", "Task", "Improvement", "New Feature"}


def sections(issues: list[Issue]) -> dict[str, list[Issue]]:
    done = [i for i in issues if i.status_category == "done"]
    return {
        "features": [i for i in done if i.issue_type in FEATURE_TYPES],
        "bug_fixes": [i for i in done if i.issue_type == "Bug"],
        "known_issues": [i for i in issues if i.status_category != "done" and (i.issue_type == "Bug" or is_blocker(i))],
    }


def page_title(project_key: str, version: str) -> str:
    return f"{project_key} {version} Release Notes"


def _issue_list(items: list[Issue], browse_url) -> str:
    if not items:
        return "<p><em>None</em></p>"
    rows = "".join(
        f'<li><a href="{escape(browse_url(i.key))}">{escape(i.key)}</a> {escape(i.summary)}'
        f" <em>({escape(i.status)})</em></li>"
        for i in items
    )
    return f"<ul>{rows}</ul>"


def build_html(project_key: str, version: str, issues: list[Issue], readiness: Readiness, browse_url) -> str:
    s = sections(issues)
    return (
        f"<p>Generated by Release Readiness Dashboard on {date.today().isoformat()}.</p>"
        f"<h2>Status</h2>"
        f"<p><strong>{readiness.percent_ready}% ready</strong>: {readiness.done} of {readiness.total} issues done, "
        f"{readiness.in_progress} in progress, {readiness.to_do} to do, {len(readiness.blockers)} blockers.</p>"
        f"<h2>Features</h2>{_issue_list(s['features'], browse_url)}"
        f"<h2>Bug fixes</h2>{_issue_list(s['bug_fixes'], browse_url)}"
        f"<h2>Known issues</h2>{_issue_list(s['known_issues'], browse_url)}"
    )
